/**
 * Monitoring Setup Script
 * Sets up basic monitoring and logging for the application
 */

const fs = require('fs');
const path = require('path');

// Create monitoring directories
const monitoringDir = path.join(__dirname, '../monitoring');
const logsDir = path.join(__dirname, '../logs');

[monitoringDir, logsDir].forEach(dir => {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
    console.log(`✓ Created directory: ${dir}`);
  }
});

// Create monitoring configuration
const monitoringConfig = {
  metrics: {
    enabled: true,
    interval: 60000, // 1 minute
    endpoints: [
      '/api/v1/analytics/cache-performance',
      '/api/v1/analytics/recommendation-quality',
    ],
  },
  alerts: {
    enabled: true,
    thresholds: {
      responseTime: 1000, // ms
      errorRate: 0.05, // 5%
      cacheHitRate: 0.70, // 70%
    },
  },
  logging: {
    level: process.env.LOG_LEVEL || 'info',
    maxFiles: 30,
    maxSize: '20m',
  },
};

const configPath = path.join(monitoringDir, 'config.json');
fs.writeFileSync(configPath, JSON.stringify(monitoringConfig, null, 2));
console.log(`✓ Created monitoring config: ${configPath}`);

// Create metrics collection script
const metricsScript = `
/**
 * Metrics Collection
 * Auto-generated by monitor-setup.js
 */

const axios = require('axios');
const fs = require('fs');
const path = require('path');

const API_URL = process.env.API_URL || 'http://localhost:5000/api/v1';
const METRICS_FILE = path.join(__dirname, 'metrics.json');

async function collectMetrics() {
  const timestamp = new Date().toISOString();
  const metrics = { timestamp };
  
  try {
    // Collect cache performance
    const cacheResp = await axios.get(\`\${API_URL}/analytics/cache-performance\`, {
      headers: { Authorization: \`Bearer \${process.env.ADMIN_TOKEN}\` }
    });
    metrics.cache = cacheResp.data.data;
    
    // Collect recommendation quality
    const qualityResp = await axios.get(\`\${API_URL}/analytics/recommendation-quality?days=1\`, {
      headers: { Authorization: \`Bearer \${process.env.ADMIN_TOKEN}\` }
    });
    metrics.quality = qualityResp.data.data;
    
    // Append to metrics file
    let allMetrics = [];
    if (fs.existsSync(METRICS_FILE)) {
      allMetrics = JSON.parse(fs.readFileSync(METRICS_FILE, 'utf8'));
    }
    allMetrics.push(metrics);
    
    // Keep only last 1000 entries
    if (allMetrics.length > 1000) {
      allMetrics = allMetrics.slice(-1000);
    }
    
    fs.writeFileSync(METRICS_FILE, JSON.stringify(allMetrics, null, 2));
    console.log(\`✓ Metrics collected at \${timestamp}\`);
    
  } catch (error) {
    console.error(\`✗ Metrics collection failed: \${error.message}\`);
  }
}

// Run immediately
collectMetrics();

// Schedule every minute
setInterval(collectMetrics, 60000);
`;

const metricsPath = path.join(monitoringDir, 'collect-metrics.js');
fs.writeFileSync(metricsPath, metricsScript);
console.log(`✓ Created metrics collector: ${metricsPath}`);

// Create README
const readme = `# Monitoring Setup

## Configuration

Monitoring configuration is in \`config.json\`.

## Metrics Collection

To start collecting metrics:

\`\`\`bash
node monitoring/collect-metrics.js
\`\`\`

Metrics will be stored in \`monitoring/metrics.json\`.

## Environment Variables

Set these for the metrics collector:
- \`API_URL\`: Backend API URL (default: http://localhost:5000/api/v1)
- \`ADMIN_TOKEN\`: JWT token for authenticated routes

## Monitoring Endpoints

Available analytics endpoints:
- GET /api/v1/analytics/ab-testing
- GET /api/v1/analytics/recommendation-quality
- GET /api/v1/analytics/taste-calibration
- GET /api/v1/analytics/cache-performance

## Logs

Application logs are stored in \`logs/\` directory.
`;

const readmePath = path.join(monitoringDir, 'README.md');
fs.writeFileSync(readmePath, readme);
console.log(`✓ Created README: ${readmePath}`);

console.log('\n' + '='.repeat(60));
console.log('✓ Monitoring setup complete!');
console.log('='.repeat(60));
console.log('\nNext steps:');
console.log('1. Set ADMIN_TOKEN environment variable');
console.log('2. Run: node monitoring/collect-metrics.js');
console.log('3. View metrics in: monitoring/metrics.json');
console.log('='.repeat(60));
